class RunCommandTest(unittest.TestCase):
    # Split output markers so the logged command source cannot satisfy assertions.
    def run_python(self, source, **kwargs):
        output = io.StringIO()
        with contextlib.redirect_stderr(output):
            result = build_node_modules.run_command(
                [sys.executable, "-c", source], **kwargs
            )
        return result, output.getvalue()

    def test_verbose_stdout_and_stderr_do_not_block(self):
        for stream in ("stdout", "stderr"):
            with self.subTest(stream=stream):
                result, output = self.run_python(
                    f"import sys; sys.{stream}.write('x' * (2 * 1024 * 1024))",
                    timeout=10,
                )
                self.assertEqual(result, 0, output)
                self.assertNotIn("timed out", output)

    def test_success_respects_cwd_and_keeps_output_quiet(self):
        with tempfile.TemporaryDirectory() as directory:
            Path(directory, "input.txt").write_text("ready")
            result, output = self.run_python(
                "from pathlib import Path; "
                "assert Path('input.txt').read_text() == 'ready'; "
                "print('quiet-' + 'success')",
                cwd=directory,
            )
        self.assertEqual(result, 0, output)
        self.assertNotIn("quiet-success", output)

    def test_failure_preserves_exit_code_and_both_streams(self):
        result, output = self.run_python(
            "import sys; print('output-' + 'marker'); "
            "print('error-' + 'marker', file=sys.stderr); sys.exit(7)"
        )
        self.assertEqual(result, 7)
        self.assertIn("Command failed with exit code 7", output)
        self.assertIn("STDOUT:\noutput-marker", output)
        self.assertIn("STDERR:\nerror-marker", output)

    def test_timeout_retains_output_and_reaps_process(self):
        processes = []
        original_popen = subprocess.Popen

        def capture_process(*args, **kwargs):
            process = original_popen(*args, **kwargs)
            processes.append(process)
            return process

        with patch.object(subprocess_util.subprocess, "Popen", capture_process):
            result, output = self.run_python(
                "import sys,time; print('partial-' + 'out', flush=True); "
                "print('partial-' + 'err', file=sys.stderr, flush=True); time.sleep(5)",
                timeout=0.5,
            )
        self.assertEqual(result, 1)
        self.assertIn("timed out after 0.5 seconds", output)
        self.assertIn("STDOUT:\npartial-out", output)
        self.assertIn("STDERR:\npartial-err", output)
        self.assertEqual(processes[0].returncode, -signal.SIGKILL)
        self.assertTrue(processes[0].stdout.closed)
        self.assertTrue(processes[0].stderr.closed)

    def test_timeout_stops_children_holding_output_pipes(self):
        for parent_wait in (True, False):
            with self.subTest(parent_wait=parent_wait), tempfile.TemporaryDirectory() as directory:
                # A surviving child would create this file, not merely delay us.
                marker = Path(directory, "survived")
                child = f"import time,pathlib; time.sleep(2); pathlib.Path({str(marker)!r}).touch()"
                source = (
                    "import subprocess,sys; "
                    f"child = subprocess.Popen([sys.executable, '-c', {child!r}]); "
                    "print('child-' + 'started', flush=True); "
                    + ("child.wait()" if parent_wait else "sys.exit(0)")
                )
                result, output = self.run_python(source, timeout=0.5)
                self.assertEqual(result, 1)
                self.assertIn("STDOUT:\nchild-started", output)
                time.sleep(2.5)
                self.assertFalse(marker.exists(), output)

    def test_timeout_handles_process_group_already_gone(self):
        original_killpg = os.killpg

        def kill_then_report_missing(group, sig):
            original_killpg(group, sig)
            raise ProcessLookupError

        with patch.object(subprocess_util.os, "killpg", kill_then_report_missing):
            result, output = self.run_python("import time; time.sleep(5)", timeout=0.1)
        self.assertEqual(result, 1)
        self.assertIn("timed out", output)
        self.assertNotIn("Error running command", output)

    def test_missing_executable_returns_failure(self):
        with tempfile.TemporaryDirectory() as directory:
            output = io.StringIO()
            with contextlib.redirect_stderr(output):
                result = build_node_modules.run_command([str(Path(directory, "missing"))])
        self.assertEqual(result, 1)
        self.assertIn("Error running command", output.getvalue())

    def test_all_three_scripts_use_the_shared_runner(self):
        root = Path(__file__).resolve().parents[1]
        for relative in ("workspace-pnpm/build_node_modules.py",
                         "workspace-pnpm/build_next_build.py",
                         "simple-pnpm/build_node_modules.py"):
            with self.subTest(script=relative):
                spec = importlib.util.spec_from_file_location("script_under_test", root / relative)
                module = importlib.util.module_from_spec(spec)
                spec.loader.exec_module(module)
                self.assertIs(module.run_command, subprocess_util.run_command)

    def test_env_forwarding_and_signal_exit_code(self):
        result, output = self.run_python(
            "import os,signal; assert os.environ['PNPM_TEST_VALUE'] == 'present'; "
            "os.kill(os.getpid(), signal.SIGTERM)",
            env={"PNPM_TEST_VALUE": "present"},
        )
        self.assertEqual(result, -signal.SIGTERM, output)

    def test_sigterm_handler_is_restored_on_success_and_startup_failure(self):
        original = signal.getsignal(signal.SIGTERM)
        self.run_python("pass")
        self.assertIs(signal.getsignal(signal.SIGTERM), original)
        self.test_missing_executable_returns_failure()
        self.assertIs(signal.getsignal(signal.SIGTERM), original)

    def test_runner_can_be_used_outside_main_thread(self):
        results = []
        thread = threading.Thread(target=lambda: results.append(self.run_python("pass")))
        thread.start()
        thread.join(timeout=10)
        self.assertFalse(thread.is_alive())
        self.assertEqual(results[0][0], 0, results)

    def test_sigterm_raises_an_exit_for_cleanup(self):
        with self.assertRaises(SystemExit) as raised:
            subprocess_util._terminate(signal.SIGTERM, None)
        self.assertEqual(raised.exception.code, 128 + signal.SIGTERM)

    def test_group_permission_error_preserves_timeout_output(self):
        real_killpg = os.killpg

        def kill_then_report_denied(group, sig):
            real_killpg(group, sig)
            raise PermissionError("group denied")

        with patch.object(subprocess_util.os, "killpg", kill_then_report_denied):
            result, output = self.run_python(
                "import time; print('partial-' + 'out', flush=True); time.sleep(30)",
                timeout=0.5,
            )
        self.assertEqual(result, 1)
        self.assertIn("could not kill process group: group denied", output)
        self.assertIn("timed out after 0.5 seconds", output)
        self.assertIn("STDOUT:\npartial-out", output)

    def test_detached_child_cannot_hold_cleanup_open(self):
        with tempfile.TemporaryDirectory() as directory:
            child_pid = Path(directory, "pid")
            child = (
                "import os,pathlib,time; "
                f"pathlib.Path({str(child_pid)!r}).write_text(str(os.getpid())); "
                "print('detached-' + 'out', flush=True); time.sleep(30)"
            )
            source = (
                "import subprocess,sys,time; "
                f"subprocess.Popen([sys.executable, '-c', {child!r}], start_new_session=True); "
                "time.sleep(30)"
            )
            # The outer subprocess deadline prevents a broken cleanup from
            # hanging the test job. The detached fixture is explicitly stopped.
            wrapper = (
                f"import sys; sys.path.insert(0, {str(Path(subprocess_util.__file__).parent)!r}); "
                "from subprocess_util import run_command; "
                f"sys.exit(run_command([sys.executable, '-c', {source!r}], "
                "timeout=1, cleanup_timeout=0.2))"
            )
            try:
                result = subprocess.run([sys.executable, "-c", wrapper],
                                        capture_output=True, text=True, timeout=10)
                self.assertEqual(result.returncode, 1, result.stderr)
                self.assertIn("timed out draining", result.stderr)
                self.assertIn("STDOUT:\ndetached-out", result.stderr)
            finally:
                if child_pid.exists():
                    os.kill(int(child_pid.read_text()), signal.SIGKILL)

    def test_sigint_and_sigterm_stop_the_command_subtree(self):
        for sig in (signal.SIGINT, signal.SIGTERM):
            with self.subTest(signal=sig), tempfile.TemporaryDirectory() as directory:
                ready = Path(directory, "ready")
                survived = Path(directory, "survived")
                child = (
                    "import pathlib,time; "
                    f"pathlib.Path({str(ready)!r}).touch(); "
                    "print('cancel-' + 'out', flush=True); time.sleep(2); "
                    f"pathlib.Path({str(survived)!r}).touch()"
                )
                command = (
                    "import subprocess,sys; "
                    f"subprocess.Popen([sys.executable, '-c', {child!r}]).wait()"
                )
                wrapper = (
                    f"import sys; sys.path.insert(0, {str(Path(subprocess_util.__file__).parent)!r}); "
                    "from subprocess_util import run_command; "
                    f"run_command([sys.executable, '-c', {command!r}])"
                )
                with subprocess.Popen([sys.executable, "-c", wrapper],
                                      stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                      text=True) as process:
                    try:
                        deadline = time.monotonic() + 10
                        while not ready.exists() and time.monotonic() < deadline:
                            time.sleep(0.01)
                        self.assertTrue(ready.exists(), "command did not start")
                        process.send_signal(sig)
                        _, output = process.communicate(timeout=10)
                        self.assertNotEqual(process.returncode, 0)
                        self.assertIn("STDOUT:\ncancel-out", output)
                    finally:
                        if process.poll() is None:
                            process.kill()
                            process.communicate(timeout=10)
                time.sleep(2.5)
                self.assertFalse(survived.exists(), output)

    def test_cleanup_bounds_drain_and_reap_when_kill_fails(self):
        for kill_error in (None, PermissionError("child denied")):
            with self.subTest(kill_error=kill_error):
                process = Mock(pid=123, returncode=None)
                process.communicate.side_effect = [
                    subprocess.TimeoutExpired("command", 1),
                    subprocess.TimeoutExpired("command", 0.1, output=b"partial-\xff", stderr=None),
                ]
                process.poll.return_value = None
                process.kill.side_effect = kill_error
                process.wait.side_effect = subprocess.TimeoutExpired("command", 0.1)
                with patch.object(subprocess_util.subprocess, "Popen", return_value=process), \
                     patch.object(subprocess_util.os, "killpg", side_effect=PermissionError("group denied")):
                    result, output = self.run_python("pass", timeout=1, cleanup_timeout=0.1)
                self.assertEqual(result, 1)
                process.communicate.assert_called_with(timeout=0.1)
                process.wait.assert_called_once_with(timeout=0.1)
                process.stdout.close.assert_called_once()
                process.stderr.close.assert_called_once()
                process.kill.assert_called_once()
                self.assertIn("STDOUT:\npartial-\ufffd", output)
                self.assertIn("could not be reaped", output)
                if kill_error:
                    self.assertIn("could not kill command: child denied", output)

    def test_unexpected_read_error_cleans_up_and_preserves_diagnostics(self):
        process = Mock(pid=123, returncode=-signal.SIGKILL)
        process.communicate.side_effect = [OSError("read failed"), ("partial-out", "partial-err")]
        with patch.object(subprocess_util.subprocess, "Popen", return_value=process), \
             patch.object(subprocess_util.os, "killpg") as killpg:
            result, output = self.run_python("pass")
        self.assertEqual(result, 1)
        killpg.assert_called_once_with(123, signal.SIGKILL)
        self.assertIn("STDOUT:\npartial-out", output)
        self.assertIn("STDERR:\npartial-err", output)
        self.assertIn("Error running command: read failed", output)

    def test_cleanup_does_not_kill_an_already_reaped_parent(self):
        process = Mock(pid=123, returncode=0)
        process.communicate.side_effect = [
            subprocess.TimeoutExpired("command", 1),
            subprocess.TimeoutExpired("command", 0.1, output=b"detached-out", stderr=b"detached-err"),
        ]
        process.poll.return_value = 0
        with patch.object(subprocess_util.subprocess, "Popen", return_value=process), \
             patch.object(subprocess_util.os, "killpg", side_effect=ProcessLookupError):
            result, output = self.run_python("pass", timeout=1, cleanup_timeout=0.1)
        self.assertEqual(result, 1)
        process.kill.assert_not_called()
        process.wait.assert_called_once_with(timeout=0.1)
        self.assertIn("STDOUT:\ndetached-out", output)
        self.assertIn("STDERR:\ndetached-err", output)


class ScriptIntegrationTest(unittest.TestCase):
    def test_verbose_commands_through_each_script(self):
        scripts = ("simple-pnpm/build_node_modules.py",
                   "workspace-pnpm/build_node_modules.py",
                   "workspace-pnpm/build_next_build.py")
        for relative in scripts:
            for failure in (False, True):
                with self.subTest(script=relative, failure=failure), tempfile.TemporaryDirectory() as directory:
                    root = Path(directory)
                    bin_dir = root / "bin"
                    bin_dir.mkdir()
                    source = (
                        f"#!{sys.executable}\n"
                        "import os,pathlib,sys\n"
                        "name = pathlib.Path(sys.argv[0]).name\n"
                        "sys.stdout.write('x' * (2 * 1024 * 1024))\n"
                        "sys.stderr.write('y' * (2 * 1024 * 1024))\n"
                        "if os.environ.get('FAIL_TOOL') == name: sys.exit(7)\n"
                        "if name == 'turbo':\n"
                        "    out = pathlib.Path(sys.argv[sys.argv.index('--out-dir') + 1])\n"
                        "    (out / 'json').mkdir()\n"
                        "    (out / 'pnpm-lock.yaml').write_text('lockfileVersion: 9')\n"
                        "elif name == 'pnpm':\n"
                        "    assert sys.argv[1:] == ['install', '--frozen-lockfile']\n"
                        "    pathlib.Path('node_modules').mkdir()\n"
                        "else:\n"
                        "    assert os.environ['BUILD_VALUE'] == 'forwarded'\n"
                        "    pathlib.Path('.next').mkdir()\n"
                    )
                    for name in ("pnpm", "turbo"):
                        tool = bin_dir / name
                        tool.write_text(source)
                        tool.chmod(0o755)
                    app = root / "app"
                    (app / "node_modules/.bin").mkdir(parents=True)
                    next_bin = app / "node_modules/.bin/next"
                    next_bin.write_text(source)
                    next_bin.chmod(0o755)
                    out = root / "out/result"
                    toolchains = Path(__file__).resolve().parents[1]
                    if "PNPM_TEST_BUILD_ROOT" in os.environ:
                        # Optional local validation of the actual Buck artifacts.
                        part = Path(relative)
                        script = Path(os.environ["PNPM_TEST_BUILD_ROOT"]) / part.parent / f"__{part.name}__" / "script" / part.name
                    else:
                        script = toolchains / relative
                    if relative.startswith("simple"):
                        args = ["--root-dir", str(root), str(out)]
                        command = "pnpm"
                    elif relative.endswith("build_next_build.py"):
                        args = ["--root-dir", str(root), "--package-dir", "app",
                                "--build-env", "BUILD_VALUE=forwarded", str(out)]
                        command = "next"
                    else:
                        args = ["--package-dir", "app", "--turbo-bin", str(bin_dir / "turbo"), str(out)]
                        command = "pnpm"
                    env = {**os.environ, "PATH": str(bin_dir), "PYTHONPATH": "",
                           "FAIL_TOOL": command if failure else ""}
                    result = subprocess.run([sys.executable, str(script), *args], cwd=root,
                                            env=env, capture_output=True, text=True, timeout=20)
                    self.assertEqual(result.returncode, 7 if failure else 0, result.stderr[-2000:])
                    if failure:
                        self.assertIn("STDOUT:\nxxx", result.stderr)
                        self.assertIn("STDERR:\nyyy", result.stderr)
                    else:
                        self.assertTrue((out / (".next" if command == "next" else "node_modules")).is_dir())


