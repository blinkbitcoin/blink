#!/usr/bin/env python3
"""Run with python3 -m unittest discover -s toolchains/workspace-pnpm -v."""
import contextlib
import io
import os
from pathlib import Path
import signal
import subprocess
import sys
import tempfile
import time
import unittest
from unittest.mock import patch

import build_node_modules


class RunCommandTest(unittest.TestCase):
    def run_python(self, source, **kwargs):
        output = io.StringIO()
        with contextlib.redirect_stderr(output):
            result = build_node_modules.run_command(
                [sys.executable, "-c", source], **kwargs
            )
        return result, output.getvalue()

    def test_verbose_stdout_and_stderr_do_not_block(self):
        for stream in ("stdout", "stderr"):
            with self.subTest(stream=stream):
                result, output = self.run_python(
                    f"import sys; sys.{stream}.write('x' * (2 * 1024 * 1024))",
                    timeout=2,
                )
                self.assertEqual(result, 0, output)
                self.assertNotIn("timed out", output)

    def test_success_respects_cwd_and_keeps_output_quiet(self):
        with tempfile.TemporaryDirectory() as directory:
            Path(directory, "input.txt").write_text("ready")
            result, output = self.run_python(
                "from pathlib import Path; "
                "assert Path('input.txt').read_text() == 'ready'; "
                "print('quiet-' + 'success')",
                cwd=directory,
            )
        self.assertEqual(result, 0, output)
        self.assertNotIn("quiet-success", output)

    def test_failure_preserves_exit_code_and_both_streams(self):
        result, output = self.run_python(
            "import sys; print('output-' + 'marker'); "
            "print('error-' + 'marker', file=sys.stderr); sys.exit(7)"
        )
        self.assertEqual(result, 7)
        self.assertIn("Command failed with exit code 7", output)
        self.assertIn("STDOUT:\noutput-marker", output)
        self.assertIn("STDERR:\nerror-marker", output)

    def test_timeout_retains_output_and_reaps_process(self):
        processes = []
        original_popen = subprocess.Popen

        def capture_process(*args, **kwargs):
            process = original_popen(*args, **kwargs)
            processes.append(process)
            return process

        with patch.object(build_node_modules.subprocess, "Popen", capture_process):
            result, output = self.run_python(
                "import sys,time; print('partial-' + 'out', flush=True); "
                "print('partial-' + 'err', file=sys.stderr, flush=True); time.sleep(5)",
                timeout=0.5,
            )
        self.assertEqual(result, 1)
        self.assertIn("timed out after 0.5 seconds", output)
        self.assertIn("STDOUT:\npartial-out", output)
        self.assertIn("STDERR:\npartial-err", output)
        self.assertEqual(processes[0].returncode, -signal.SIGKILL)
        self.assertTrue(processes[0].stdout.closed)
        self.assertTrue(processes[0].stderr.closed)

    def test_timeout_stops_children_holding_output_pipes(self):
        # Cover both a running parent and one that exited while its child kept
        # the pipes open. The child's finite sleep bounds failures of this test.
        for parent_wait in (True, False):
            with self.subTest(parent_wait=parent_wait):
                source = (
                    "import subprocess,sys,time; "
                    "child = subprocess.Popen([sys.executable, '-c', "
                    "'import time; time.sleep(4)']); "
                    "print('child-' + 'started', flush=True); "
                    + ("child.wait()" if parent_wait else "sys.exit(0)")
                )
                started = time.monotonic()
                result, output = self.run_python(source, timeout=0.5)
                self.assertLess(time.monotonic() - started, 3)
                self.assertEqual(result, 1)
                self.assertIn("STDOUT:\nchild-started", output)

    def test_timeout_handles_process_group_already_gone(self):
        original_killpg = os.killpg

        def kill_then_report_missing(group, sig):
            original_killpg(group, sig)
            raise ProcessLookupError

        with patch.object(build_node_modules.os, "killpg", kill_then_report_missing):
            result, output = self.run_python("import time; time.sleep(5)", timeout=0.1)
        self.assertEqual(result, 1)
        self.assertIn("timed out", output)
        self.assertNotIn("Error running command", output)

    def test_missing_executable_returns_failure(self):
        with tempfile.TemporaryDirectory() as directory:
            output = io.StringIO()
            with contextlib.redirect_stderr(output):
                result = build_node_modules.run_command([str(Path(directory, "missing"))])
        self.assertEqual(result, 1)
        self.assertIn("Error running command", output.getvalue())


if __name__ == "__main__":
    unittest.main()
